        "BYBIT_ACCOUNT_REFRESH_INTERVAL_SECONDS",
        "TELEGRAM_BOT_TOKEN",
        "TELEGRAM_CHAT_ID",
        "LLM_API_KEY",
        "NEWS_CLASSIFIER_MODE",
        "LLM_PROVIDER_NAME",
        "LLM_API_URL",
        "LLM_MODEL",
        "LLM_CLASSIFIER_VERSION",
        "LLM_ALLOW_MOCK_FALLBACK",
        "LLM_CACHE_TTL_SECONDS",
