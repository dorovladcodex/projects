        "LLM_CIRCUIT_BREAKER_FAILURE_THRESHOLD",
        "LLM_CIRCUIT_BREAKER_COOLDOWN_SECONDS",
        "LLM_MAX_INPUT_CHARACTERS",
        "LLM_MAX_OUTPUT_TOKENS",
        "LLM_HOURLY_REQUEST_BUDGET",
        "LLM_DAILY_REQUEST_BUDGET",
